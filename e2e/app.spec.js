import { expect, test } from '@playwright/test'
import { randomBytes } from 'node:crypto'

test('full grocery workflow', async ({ page }) => {
  await page.goto('/')
  const password = randomBytes(20).toString('hex')
  async function createAccount(username) {
    await page.getByRole('button', { name: 'Create an account', exact: true }).click()
    await page.getByLabel('Username').fill(username)
    await page.getByLabel('Password').fill(password)
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await expect(page.getByText(/set up your groceries/)).toBeVisible()
  }
  await createAccount('first-shopper')

  // Onboarding
  await expect(page.getByText(/set up your groceries/)).toBeVisible()
  await expect(page.getByLabel('New item name')).toHaveCount(0)
  await page.getByRole('button', { name: 'Deal Checker', exact: true }).click()
  await page.getByLabel('Deal price').fill('3.50')
  await page.getByLabel('Deal unit').selectOption('L')
  await page.getByLabel('Deal quantity').fill('0.5')
  await expect(page.getByRole('status')).toHaveText('$0.70 / 100 mL')
  await page.getByLabel('Deal unit').selectOption('kg')
  await expect(page.getByRole('status')).toHaveText('$0.70 / 100 g')
  await page.getByLabel('Deal quantity').fill('0')
  await expect(page.getByRole('alert')).toContainText('Quantity must be greater than zero.')
  await page.getByRole('button', { name: 'Deal Checker', exact: true }).click()
  await expect(page.getByLabel('Deal price')).toHaveCount(0)
  await page.getByRole('button', { name: 'Add new item', exact: true }).click()
  await page.getByLabel('New item name').fill('Milk')
  await page.getByLabel('New item category').selectOption('fridge')
  const packageSize = page.getByLabel('Package size, optional')
  const packageUnit = page.getByLabel('Package unit', { exact: true })
  await packageSize.fill('500')
  await packageUnit.selectOption('mL')
  const initialPrice = page.getByLabel('Package price (optional)', { exact: true })
  const initialStore = page.getByLabel('Store (required with price)', { exact: true })
  await initialPrice.fill('3.50')
  await page.getByRole('button', { name: 'Add item' }).click()
  await expect(initialStore).toBeFocused()
  await initialStore.fill('Costco')
  await page.getByRole('button', { name: 'Add item' }).click()
  const milk = page.getByRole('row', { name: /Milk/ })
  await expect(milk.getByText('500 mL', { exact: true })).toBeVisible()
  await expect(milk.getByText('$3.50 at Costco')).toBeVisible()
  await expect(milk.getByText('$0.70 / 100 mL', { exact: true })).toBeVisible()
  await expect(page.getByLabel('New item name')).toHaveCount(0)
  await page.getByRole('button', { name: 'Add new item', exact: true }).click()
  await expect(packageSize).toBeEmpty()
  await expect(initialPrice).toBeEmpty()
  await expect(initialStore).toBeEmpty()
  for (const [name, cat] of [['Apples', 'produce'], ['Rice', 'pantry'], ['Soap', 'household'], ['Tmp', 'meat']]) {
    await page.getByLabel('New item name').fill(name)
    await page.getByLabel('New item category').selectOption(cat)
    await page.getByRole('button', { name: 'Add item' }).click()
    await expect(page.getByRole('cell', { name, exact: true })).toBeVisible()
  }

  await page.getByLabel('New item name').fill('Facial tissue')
  await page.getByLabel('New item category').selectOption('household')
  await packageUnit.selectOption('count')
  await packageSize.fill('6')
  await initialPrice.fill('9.00')
  await initialStore.fill('Costco')
  await page.getByRole('button', { name: 'Add item' }).click()
  const tissue = page.getByRole('row', { name: /Facial tissue/ })
  await expect(tissue.getByText('6-pack', { exact: true })).toBeVisible()
  await expect(tissue.getByText('$1.50 each', { exact: true })).toBeVisible()

  // Edit and delete
  await page.getByRole('row', { name: /Tmp/ }).getByRole('button', { name: 'Edit' }).click()
  await page.getByLabel('Edit name').fill('Beef')
  await page.getByLabel('Edit category').selectOption('meat')
  await page.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Beef', exact: true })).toBeVisible()
  await page.getByRole('row', { name: /Beef/ }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByRole('cell', { name: 'Beef', exact: true })).toHaveCount(0)
  await expect(milk).toBeVisible()

  // Weekly purchases
  await page.getByLabel('Apples weekly').click()
  await expect(page.getByLabel('Apples weekly')).toBeChecked()
  await page.getByLabel('Apples per week').fill('4')
  await page.getByLabel('Apples per week').blur()
  await page.getByRole('button', { name: 'weekly purchases' }).click()
  await expect(page.getByRole('cell', { name: 'Apples', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'Rice', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Apples per week')).toHaveValue('4')
  await page.getByRole('button', { name: 'all items' }).click()

  // Filter by name as you type; clearing the search restores the list.
  const search = page.getByRole('searchbox', { name: 'Search items' })
  await search.pressSequentially('TISS')
  await expect(tissue).toBeVisible()
  await expect(milk).toHaveCount(0)
  await search.fill('no matching grocery item')
  await expect(page.getByText('No items match your filters.')).toBeVisible()
  await search.clear()
  await expect(milk).toBeVisible()
  await expect(tissue).toBeVisible()

  // Filter by category
  await page.getByRole('button', { name: 'fridge', exact: true }).click()
  await expect(milk).toBeVisible()
  await expect(tissue).toHaveCount(0)
  await page.getByRole('button', { name: 'produce', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Apples', exact: true })).toBeVisible()
  await expect(milk).toHaveCount(0)
  await page.getByRole('button', { name: 'all', exact: true }).click()

  // Edit item details and store prices from the same row action.
  await milk.getByRole('button', { name: 'Edit' }).click()
  const editSize = page.getByLabel('Edit package size')
  await editSize.fill('0.25')
  await page.getByLabel('Edit package unit').selectOption('L')
  await page.getByLabel('Store', { exact: true }).fill('Aldi')
  await page.getByLabel('Price', { exact: true }).fill('2.75')
  await page.getByRole('button', { name: 'Save price' }).click()
  const costcoPrice = page.getByLabel('Remove Costco price').locator('..')
  await expect(costcoPrice.getByText('$0.70 / 100 mL', { exact: true })).toBeVisible()
  const aldiPrice = page.getByLabel('Remove Aldi price').locator('..')
  await expect(aldiPrice.getByText('$0.55 / 100 mL', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Remove Costco price' }).click()
  await expect(costcoPrice).toHaveCount(0)
  await expect(editSize).toHaveValue('0.25')
  await page.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(page.getByText('Store prices')).toHaveCount(0)
  await expect(milk.getByText('$2.75 at Aldi')).toBeVisible()
  await expect(milk.getByText('$1.10 / 100 mL', { exact: true })).toBeVisible()
  await page.reload()
  await expect(milk.getByText('0.25 L', { exact: true })).toBeVisible()
  await expect(milk.getByText('$2.75 at Aldi')).toBeVisible()
  await expect(tissue.getByText('$1.50 each', { exact: true })).toBeVisible()

  // Inventory: have 1, want 3
  await page.getByLabel('Milk target').fill('3')
  await page.getByLabel('Milk quantity').fill('1')
  await page.getByLabel('Milk quantity').blur()
  await expect(page.getByLabel('Milk quantity')).toHaveValue('1')

  // Generate list from inventory
  await page.getByRole('button', { name: 'Shopping Lists' }).click()
  await page.getByRole('button', { name: 'Generate from inventory' }).click()
  await expect(page.getByRole('checkbox', { name: /Milk/ })).toBeVisible()
  await expect(page.getByText('Estimated total: $5.50')).toBeVisible()

  // Purchase updates inventory
  await page.getByRole('checkbox').click()
  await expect(page.getByRole('checkbox')).toBeChecked()
  await page.getByRole('button', { name: 'Inventory', exact: true }).click()
  await expect(page.getByLabel('Milk quantity')).toHaveValue('3')

  // Manual list
  await page.getByRole('button', { name: 'Shopping Lists' }).click()
  await page.getByLabel('New list name').fill('Party')
  await page.getByRole('button', { name: 'Create list' }).click()
  await page.getByLabel('Item to add').selectOption({ label: 'Soap' })
  await page.getByRole('button', { name: 'Add to list' }).click()
  await expect(page.getByRole('checkbox', { name: /Soap/ })).toBeVisible()

  await page.getByRole('button', { name: 'Sign out' }).click()
  await createAccount('second-shopper')
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.getByLabel('Username').fill('first-shopper')
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(milk).toBeVisible()
})
